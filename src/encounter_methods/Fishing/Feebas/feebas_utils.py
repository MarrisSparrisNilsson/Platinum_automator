def make_feebas_fishing_movement(tiles: list, tile: int, walk_to_pos: bool):
    walk_dir = tiles[tile]
    turn_dir = tiles[tile + 1 if (tile + 1) < len(tiles) else tile]

    if take_step(tile):
        controls.move(walk_dir, 1)  # Step

    # If a new repel was activated, and we should continue fishing instead of walking
    if check_repel_status() and not walk_to_pos:
        # Resumes encounter detection
        PauseStateManager.get_instance().get_encounter_pause_state().set()

    # Prevents double steps and overstepping
    if not take_step(tile) or not turn_dir == walk_dir:
        controls.move(turn_dir, 0)  # Turn


def non_cleared_tile_ranges(tile_ranges: list[tuple[int, int]], index: int) -> None:
    """
    Tile ranges are represented as a list of tuples, where each tuple contains the start and end indices of a range.
    Tile_ranges are modified in place to remove the specified index from the ranges. If the index is found within a range,
    that range is split into two new ranges (if applicable) that exclude the index. Otherwise, the ranges are left unchanged.
    """
    for i, (start, end) in enumerate(tile_ranges):
        if start <= index <= end:
            replacement = []

            if start < index:
                replacement.append((start, index - 1))

            if index < end:
                replacement.append((index + 1, end))

            tile_ranges[i : i + 1] = replacement
            return


def get_cleared_tiles(feebas_info: dict, num_tiles: int) -> list[tuple[int, int]]:
    """
    Get the cleared tiles from the Feebas state information.

    :param feebas_info: A dictionary containing Feebas state information.
    :param num_tiles: The total number of tiles in the area.
    :return: A list of tuples representing the cleared tile ranges.
    """
    return [tuple(pair) for pair in feebas_info.get("non_cleared_tiles", [])] or [(0, num_tiles - 1)]


def get_cleared_percentage(tile_ranges: list[tuple[int, int]], total_tiles: int) -> float:
    """
    Calculate the percentage of cleared tiles based on the provided tile ranges and total number of tiles.

    :param tile_ranges: A list of tuples representing the ranges of cleared tiles.
    :param total_tiles: The total number of tiles in the area.
    :return: The percentage of cleared tiles as a float.
    """
    cleared_tiles = sum(end - start + 1 for start, end in tile_ranges)
    return (1 - (cleared_tiles / total_tiles)) * 100 if total_tiles > 0 else 0.0
